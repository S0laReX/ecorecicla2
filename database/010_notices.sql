CREATE TABLE IF NOT EXISTS Notice (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 internalUUID CHAR(36) NOT NULL UNIQUE,
 recipientUserId BIGINT UNSIGNED NOT NULL,
 kind ENUM('ACCEPTED','CONFIRMED','RATE','APPROVED','REJECTED') NOT NULL,
 eventUUID CHAR(36) NOT NULL,
 title VARCHAR(120) NOT NULL,
 body VARCHAR(1000) NOT NULL,
 createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 readAt DATETIME(3) NULL,
 UNIQUE KEY uq_notice_event (recipientUserId,kind,eventUUID),
 KEY ix_notice_inbox (recipientUserId,readAt,createdAt,id),
 CONSTRAINT fk_notice_recipient FOREIGN KEY (recipientUserId) REFERENCES User(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
